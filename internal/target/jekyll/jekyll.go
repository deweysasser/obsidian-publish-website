// Package jekyll exports published pages as a collection for a Jekyll site
// (e.g. GitHub Pages' default generator).
package jekyll

import (
	"fmt"
	"path"
	"regexp"
	"strings"

	"github.com/deweysasser/obsidian-publish-website/internal/config"
	"github.com/deweysasser/obsidian-publish-website/internal/render"
	"github.com/deweysasser/obsidian-publish-website/internal/selector"
	"github.com/deweysasser/obsidian-publish-website/internal/target"
	"github.com/deweysasser/obsidian-publish-website/internal/urls"
	"gopkg.in/yaml.v3"
)

// endrawRe matches every spelling Liquid accepts as the raw terminator.
var endrawRe = regexp.MustCompile(`\{%-?\s*endraw\s*-?%\}`)

// ConfigFile is the collection config snippet written next to the export.
const ConfigFile = "_config.obsidian-publish.yml"

// Target writes _<collection>/ and assets/<collection>/ under the output dir.
type Target struct {
	cfg        *config.Config
	collection string
	scheme     urls.Basic
	docs       string
	assets     string
	Warn       func(string)
	folders    map[string]bool
}

// New creates the jekyll target.
func New(cfg *config.Config) *Target {
	base := urls.BasePathOf(cfg.Site.BaseURL)
	c := cfg.Jekyll.Collection
	return &Target{
		cfg: cfg, collection: c,
		// Jekyll has no tag pages by default, so tags render unlinked.
		scheme: urls.Basic{PagePrefix: base + c + "/", AssetPrefix: base + "assets/" + c + "/"},
		docs:   path.Join(cfg.Output, "_"+c),
		assets: path.Join(cfg.Output, "assets", c),
		Warn:   func(string) {},
	}
}

func (t *Target) Scheme() urls.Scheme { return t.scheme }
func (t *Target) Mode() render.Mode   { return render.ModeMarkdown }

func (t *Target) Prepare() error {
	if err := target.CleanDir(t.docs); err != nil {
		return err
	}
	return target.CleanDir(t.assets)
}

func (t *Target) file(s *target.Site, slug string) string {
	if t.folders == nil {
		t.folders = map[string]bool{}
		s.Tree.Walk(func(n *target.FolderNode) { t.folders[n.Slug] = true })
	}
	switch {
	case slug == "":
		return "index.md"
	case t.folders[slug]:
		return slug + "/index.md"
	}
	return slug + ".md"
}

func (t *Target) permalink(slug string) string {
	return "/" + t.collection + "/" + strings.TrimPrefix(slug+"/", "/")
}

func (t *Target) WritePage(s *target.Site, p *render.Page) error {
	fm := &yaml.Node{Kind: yaml.MappingNode}
	add := func(k string, v any) {
		var n yaml.Node
		_ = n.Encode(v)
		fm.Content = append(fm.Content, &yaml.Node{Kind: yaml.ScalarNode, Value: k}, &n)
	}
	add("title", p.Title)
	add("layout", "page")
	add("permalink", t.permalink(p.Slug))
	if !p.Mtime.IsZero() {
		add("date", p.Mtime.Format("2006-01-02 15:04:05 -0700"))
		add("last_modified_at", p.Mtime.Format("2006-01-02 15:04:05 -0700"))
	}
	if len(p.Tags) > 0 {
		var tags []string
		for _, tg := range p.Tags {
			tags = append(tags, selector.Slugify(strings.TrimPrefix(tg, "#")))
		}
		add("tags", tags)
	}
	if t.cfg.ExportFrontmatter && len(p.Frontmatter) > 0 {
		add("obsidian", target.ExportFrontmatter(p.Frontmatter))
	}
	return t.write(t.file(s, p.Slug), fm, p.Markdown)
}

func (t *Target) write(rel string, fm *yaml.Node, body string) error {
	head, err := yaml.Marshal(fm)
	if err != nil {
		return err
	}
	// {% raw %} keeps Liquid from interpreting {{ }} / {% %} in notes; a
	// literal {% endraw %} is split so the raw block cannot be closed early.
	body = endrawRe.ReplaceAllStringFunc(body, func(m string) string {
		return "{% endraw %}{{ '" + strings.ReplaceAll(m, "'", "") + "' }}{% raw %}"
	})
	doc := "---\n" + string(head) + "---\n{% raw %}\n" + body + "\n{% endraw %}\n"
	return target.WriteFile(t.docs, rel, []byte(doc))
}

func (t *Target) CopyAsset(a target.Asset) error {
	return target.CopyFile(a.Src, t.assets, a.Slug)
}

func (t *Target) Finalize(s *target.Site) error {
	var err error
	s.Tree.Walk(func(n *target.FolderNode) {
		if err != nil || n.Page != nil {
			return
		}
		title := n.Name
		if n.Slug == "" {
			title = s.Config.Site.Title
		}
		fm := &yaml.Node{Kind: yaml.MappingNode}
		for _, kv := range [][2]string{{"title", title}, {"layout", "page"}, {"permalink", t.permalink(n.Slug)}} {
			fm.Content = append(fm.Content, &yaml.Node{Kind: yaml.ScalarNode, Value: kv[0]}, &yaml.Node{Kind: yaml.ScalarNode, Value: kv[1]})
		}
		var b strings.Builder
		for _, f := range n.Folders {
			fmt.Fprintf(&b, "- [%s](%s)\n", f.Name, f.URL)
		}
		for _, p := range n.Pages {
			fmt.Fprintf(&b, "- [%s](%s)\n", p.Title, p.URL)
		}
		err = t.write(t.file(s, n.Slug), fm, b.String())
	})
	if err != nil {
		return err
	}
	snippet := fmt.Sprintf("# Generated by obsidian-publish-website. Merge into _config.yml or pass both:\n#   jekyll build --config _config.yml,%s\ncollections:\n  %s:\n    output: true\n", ConfigFile, t.collection)
	if err := target.WriteFile(t.cfg.Output, ConfigFile, []byte(snippet)); err != nil {
		return err
	}
	t.Warn(fmt.Sprintf("jekyll: exported %d pages to %s; enable the %q collection (see %s)", len(s.Pages), t.docs, t.collection, ConfigFile))
	return nil
}

var _ target.Target = (*Target)(nil)
