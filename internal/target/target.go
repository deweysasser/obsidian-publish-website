// Asset is an attachment to copy into the output.
type Asset struct {
	Src  string // absolute source path
	Slug string // slug path relative to the asset root
}

// FolderNode is one folder in the published tree.
type FolderNode struct {
	Name    string // display name
	Folder  string // vault folder path
	Slug    string
	URL     string
	Page    *render.Page // folder note, nil if the folder has none
	Folders []*FolderNode
	Pages   []*render.Page // pages directly in this folder, excluding the folder note
}

// Site is everything a target needs to write the output.
type Site struct {
	Config *config.Config
	Pages  []*render.Page // sorted by slug
	Tree   *FolderNode
	Tags   map[string][]*render.Page
	Assets []Asset
	Build  time.Time
	URLs   urls.Scheme
}

// Target writes a site in some output format.
type Target interface {
	Scheme() urls.Scheme
	Mode() render.Mode
	// Prepare readies the output location (refusing to clobber foreign data).
	Prepare() error
	WritePage(s *Site, p *render.Page) error
	CopyAsset(a Asset) error
	Finalize(s *Site) error
}

// Marker is the file that marks a directory as owned by this program.
const Marker = ".obsidian-publish"

// CleanDir empties dir if it is ours (contains Marker) or empty, creates it if
// missing, and refuses otherwise. It then writes the marker.
func CleanDir(dir string) error {
	entries, err := os.ReadDir(dir)
	switch {
	case errors.Is(err, os.ErrNotExist):
	case err != nil:
		return err
	case len(entries) > 0:
		if _, err := os.Stat(filepath.Join(dir, Marker)); err != nil {
			return fmt.Errorf("refusing to overwrite %s: it is not empty and was not created by obsidian-publish (no %s file)", dir, Marker)
		}
		for _, e := range entries {
			if err := os.RemoveAll(filepath.Join(dir, e.Name())); err != nil {
				return err
			}
		}
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, Marker), []byte("Generated by obsidian-publish-website. This directory is replaced on every build.\n"), 0o644)
}

// WriteFile writes data to dir/rel, creating parent directories.
func WriteFile(dir, rel string, data []byte) error {
	p := filepath.Join(dir, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	return os.WriteFile(p, data, 0o644)
}

// CopyFile copies src to dir/rel.
func CopyFile(src, dir, rel string) error {
	b, err := os.ReadFile(src)
	if err != nil {
		return err
	}
	return WriteFile(dir, rel, b)
}

// BuildTree arranges pages into the published folder hierarchy.
func BuildTree(pub *selector.Published, pages []*render.Page, u urls.Scheme) *FolderNode {
	nodes := map[string]*FolderNode{}
	for folder, slug := range pub.Folders {
		nodes[folder] = &FolderNode{Name: path.Base(folder), Folder: folder, Slug: slug, URL: u.PageURL(slug)}
	}
	for folder, n := range nodes {
		if folder == pub.Root {
			continue
		}
		if parent := nodes[path.Dir(folder)]; parent != nil {
			parent.Folders = append(parent.Folders, n)
		}
	}
	for _, p := range pages {
		folder := path.Dir(p.SourcePath)
		if fn := pub.FolderNote(folder); fn == p.SourcePath && nodes[folder] != nil {
			nodes[folder].Page = p
			if folder != pub.Root {
				nodes[folder].Name = p.Title
			}
			continue
		}
		if n := nodes[folder]; n != nil {
			n.Pages = append(n.Pages, p)
		}
	}
	root := nodes[pub.Root]
	for _, n := range nodes {
		sort.Slice(n.Folders, func(i, j int) bool { return lessFold(n.Folders[i].Name, n.Folders[j].Name) })
		sort.Slice(n.Pages, func(i, j int) bool { return lessFold(n.Pages[i].Title, n.Pages[j].Title) })
	}
	// a configured home page that is not a folder note lives at the root URL
	for _, p := range pages {
		if p.Slug == "" && root.Page == nil {
			root.Page = p
			kept := root.Pages[:0]
			for _, q := range root.Pages {
				if q != p {
					kept = append(kept, q)
				}
			}
			root.Pages = kept
		}
	}
	return root
}

func lessFold(a, b string) bool {
	la, lb := strings.ToLower(a), strings.ToLower(b)
	if la != lb {
		return la < lb
	}
	return a < b
}

// Walk visits every folder node depth-first.
func (n *FolderNode) Walk(f func(*FolderNode)) {
	f(n)
	for _, c := range n.Folders {
		c.Walk(f)
	}
}

// ExportFrontmatter prepares note frontmatter for re-serialization: YAML
// timestamps become plain dates (when time-less) or RFC 3339 strings.
func ExportFrontmatter(fm map[string]any) map[string]any {
	out := make(map[string]any, len(fm))
	for k, v := range fm {
		out[k] = exportValue(v)
	}
	return out
}

func exportValue(v any) any {
	switch x := v.(type) {
	case time.Time:
		if x.Hour() == 0 && x.Minute() == 0 && x.Second() == 0 && x.Nanosecond() == 0 {
			return x.Format("2006-01-02")
		}
		return x.Format(time.RFC3339)
	case map[string]any:
		return ExportFrontmatter(x)
	case []any:
		out := make([]any, len(x))
		for i, e := range x {
			out[i] = exportValue(e)
		}
		return out
	}
	return v
}
