// Builds internal/dataview/bridge.js from a pinned Dataview release.
// Usage: npm ci && npm run build   (DATAVIEW_TAG/DATAVIEW_SHA256 to override)
import * as esbuild from "esbuild";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const TAG = process.env.DATAVIEW_TAG ?? "0.5.68";
const SHA256 = process.env.DATAVIEW_SHA256 ?? "3f8144fb1b90653999aec9d6da50dd36bcc33c64ca07f23c9c2f916d6b8adfb9";
const here = dirname(fileURLToPath(import.meta.url));
const cache = join(here, ".cache");
const tarball = join(cache, `dataview-${TAG}.tgz`);
const srcDir = join(cache, `dataview-${TAG}`);
const out = join(here, "..", "..", "internal", "dataview", "bridge.js");

mkdirSync(cache, { recursive: true });
if (!existsSync(tarball)) {
    const url = `https://codeload.github.com/blacksmithgu/obsidian-dataview/tar.gz/refs/tags/${TAG}`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`download ${url}: ${res.status}`);
    writeFileSync(tarball, Buffer.from(await res.arrayBuffer()));
}
const sum = createHash("sha256").update(readFileSync(tarball)).digest("hex");
if (sum !== SHA256) throw new Error(`sha256 mismatch for ${tarball}: got ${sum}, want ${SHA256}`);
if (!existsSync(srcDir)) {
    mkdirSync(srcDir);
    execFileSync("tar", ["xzf", tarball, "-C", srcDir, "--strip-components=1"]);
}
const license = readFileSync(join(srcDir, "LICENSE.txt"), "utf8");

await esbuild.build({
    entryPoints: [join(here, "entry.ts")],
    bundle: true,
    platform: "node",
    format: "cjs",
    target: "node18",
    outfile: out,
    nodePaths: [join(srcDir, "src"), join(here, "node_modules")],
    alias: {
        obsidian: join(here, "stubs", "obsidian.ts"),
        localforage: join(here, "stubs", "localforage.ts"),
        "data-import/web-worker/import-manager": join(here, "stubs", "import-manager.ts"),
    },
    tsconfig: join(srcDir, "tsconfig.json"),
    banner: {
        js: `// GENERATED by tools/dataview-bridge (Dataview ${TAG}). Do not edit.\n/*\nDataview ${license.replace(/\*\//g, "* /")}*/`,
    },
    legalComments: "inline",
    logLevel: "warning",
});
console.log(`wrote ${out} (Dataview ${TAG})`);
